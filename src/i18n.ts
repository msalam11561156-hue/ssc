let currentAffiliatedEntity: string = '';

export function getCurrentAffiliatedEntity(): string {
  if (currentAffiliatedEntity) return currentAffiliatedEntity;
  try {
    const saved = localStorage.getItem('sheet_control_school_data');
    if (saved) {
      const parsed = JSON.parse(saved);
      if (parsed?.affiliatedEntity) {
        currentAffiliatedEntity = parsed.affiliatedEntity;
        return currentAffiliatedEntity;
      }
    }
  } catch {}
  return '';
}

export function setCurrentAffiliatedEntity(entity?: string) {
  currentAffiliatedEntity = entity || '';
}

export function applyEntityTerms(text: string, _entityOverride?: string): string {
  if (!text) return text;
  return text
    .replace(/المنطقة/g, 'الإدارة')
    .replace(/لمنطقة/g, 'لإدارة')
    .replace(/بمنطقة/g, 'بإدارة')
    .replace(/منطقة/g, 'إدارة')
    .replace(/بالمعاهد/g, 'بالمدارس')
    .replace(/للمعاهد/g, 'للمدارس')
    .replace(/المعاهد/g, 'المدارس')
    .replace(/بمعاهد/g, 'بمدارس')
    .replace(/لمعاهد/g, 'لمدارس')
    .replace(/معاهد/g, 'مدارس')
    .replace(/بالمعهد/g, 'بالمدرسة')
    .replace(/للمعهد/g, 'للمدرسة')
    .replace(/المعهد/g, 'المدرسة')
    .replace(/بمعهد/g, 'بمدرسة')
    .replace(/لمعهد/g, 'لمدرسة')
    .replace(/معهد/g, 'مدرسة');
}

export function syncEntityInputText(text: string, _targetEntity?: string): string {
  if (!text) return text;
  return applyEntityTerms(text);
}

